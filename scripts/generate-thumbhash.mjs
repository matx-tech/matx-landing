/**
 * Build-time script: generates ThumbHash data URLs from screenshots.
 *
 * Usage:  node scripts/generate-thumbhash.mjs
 *
 * Output:
 *   1. lib/thumbhash-strings.json    — raw ThumbHash Base64 strings
 *   2. lib/blur-placeholder-data.ts   — data URLs for inline embedding
 *
 * The data URLs are ~2.6 KB each (100×N px PNG).  Apply CSS
 * `filter: blur(20px); transform: scale(1.1)` to make them fill any
 * container seamlessly.
 */

import { rgbaToThumbHash, thumbHashToDataURL } from 'thumbhash';
import sharp from 'sharp';
import { writeFileSync, mkdirSync, existsSync } from 'fs';
import { join, dirname, basename } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const base = join(__dirname, '..');

/**
 * Generates a ThumbHash and PNG data URL for an image resized within a maximum dimension.
 * @param {string} imagePath - Path to the source image.
 * @param {number} [maxDim=100] - Maximum width or height of the resized image.
 * @returns {Promise<{base64Hash: string, dataUrl: string, width: number, height: number}>} The Base64-encoded hash, PNG data URL, and resized dimensions.
 */
async function generateThumbHash(imagePath, maxDim = 100) {
  const { data, info } = await sharp(imagePath)
    .resize(maxDim, maxDim, { fit: 'inside' })
    .ensureAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });

  const binaryHash = rgbaToThumbHash(info.width, info.height, data);
  const base64Hash = Buffer.from(binaryHash).toString('base64');
  const dataUrl = thumbHashToDataURL(binaryHash);

  return { base64Hash, dataUrl, width: info.width, height: info.height };
}

// --- Generate from source screenshots ---

const MOBILE_PATH = join(base, 'mobile-matx.png');
const DESKTOP_PATH = join(base, 'desktop-matx.png');

const missing = [MOBILE_PATH, DESKTOP_PATH].filter((path) => !existsSync(path));
if (missing.length > 0) {
  console.error(
    `\n  Missing source screenshot${missing.length > 1 ? 's' : ''}:\n` +
      missing.map((path) => `    - ${basename(path)}  (expected at ${path})`).join('\n') +
      `\n\n  Place a mobile portrait and desktop landscape screenshot in the\n` +
      `  project root, then re-run:\n` +
      `    node scripts/generate-thumbhash.mjs\n`
  );
  process.exit(1);
}

try {
  const mobile = await generateThumbHash(MOBILE_PATH);
  const desktop = await generateThumbHash(DESKTOP_PATH);

  console.log(`Mobile:  ${mobile.base64Hash}  (data URL: ${mobile.dataUrl.length} chars)`);
  console.log(`Desktop: ${desktop.base64Hash}  (data URL: ${desktop.dataUrl.length} chars)`);

  // --- Write JSON (raw hashes) ---
  const outDir = join(base, 'lib');
  mkdirSync(outDir, { recursive: true });
  writeFileSync(
    join(outDir, 'thumbhash-strings.json'),
    JSON.stringify({ mobile: mobile.base64Hash, desktop: desktop.base64Hash }, null, 2)
  );

  // --- Write TypeScript module (data URLs for build-time embedding) ---
  const tsContent = `/**
 * Blur placeholder data URLs — auto-generated by scripts/generate-thumbhash.mjs
 * Source:  mobile-matx.png (${mobile.width}×${mobile.height} thumb), desktop-matx.png (${desktop.width}×${desktop.height} thumb)
 *
 * Each data URL is a ~2.6 KB PNG rendered from a ThumbHash.
 * Apply CSS \`filter: blur(20px); transform: scale(1.1)\` to fill any container.
 *
 * Re-run \`node scripts/generate-thumbhash.mjs\` after updating source screenshots.
 */

/** Mobile (portrait) blur placeholder — data:image/png;base64,… */
export const MOBILE_DATA_URL: string = ${JSON.stringify(mobile.dataUrl)};

/** Desktop (landscape) blur placeholder — data:image/png;base64,… */
export const DESKTOP_DATA_URL: string = ${JSON.stringify(desktop.dataUrl)};
`;

  writeFileSync(join(outDir, 'blur-placeholder-data.ts'), tsContent);
  console.log(`\nWrote lib/blur-placeholder-data.ts (${tsContent.length} bytes)`);
  console.log('Done.');
} catch (err) {
  const detail = err instanceof Error ? err.message : String(err);
  console.error(
    `\n  Failed to generate thumbhash or write output files.\n` +
    `  Error: ${detail}\n` +
    `  Make sure both mobile-matx.png and desktop-matx.png are valid, decodable\n` +
    `  images and that lib/ is writable, then re-run:\n` +
    `    node scripts/generate-thumbhash.mjs\n`
  );
  process.exit(1);
}
